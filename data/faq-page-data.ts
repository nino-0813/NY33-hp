/** アンカー用 ID（例: #aio対策とは何ですか と一致させる） */
export function faqAnchorId(question: string, categoryIndex: number, itemIndex: number): string {
  const base = question.replace(/[？?。．、,\s　]+/g, "").toLowerCase()
  return base || `faq-${categoryIndex}-${itemIndex}`
}

